#Definindo geometria da órbita
class Orbita:
  def __init__(self, r, v, M):

    self.r = r        #Vetor x,y,z da posição. raio da Terra + altitude
    self.v = v        #Vetor x,y,z da velocidade
    self.M = float(M) #massa da Terra

#Definição de variáveis que serão utilizadas posteriormente
    self.j = np.array([0,0,0])
    self.e = np.array([0,0,0])
    self.a_vec = np.array([0,0,0])
    self.b_vec = np.array([0,0,0])

    self.e_mod = 0
    self.a = 0
    self.b = 0
    self.w = 0

    self.m_anomalia0 = 0
    self.e_anomalia0 = 0
    self.e_anomalia = 0
    self.m_anomalia = 0

    self.b_mod = 0
    self.r_mod = 0

  #Definindo elementos orbitais
  def elementos_orbitais(self):

    mu_terra = MU_TERRA               #Para Curtis, temos que mu_terra = 398600 km^3/s^2. Não depende da massa do cubesat
    self.r_mod = np.linalg.norm(self.r)                #Cálculo do módulo do vetor posição
    self.j = np.cross(self.r, self.v)     #Momento angular específico. O vetor momento angular define a orientação do plano orbital. Somente a componente da velocidade perpendicular ao vetor posição contribui para o momento angular
    self.e = np.cross(self.v, self.j)/mu_terra - self.r/self.r_mod #Cálculo do vetor excentricidade. Dedução a partir da página 59 do vetor plano da órbita (primeira parte da equação). Segunda parte é o vetor unitário da posição.
    #e=0: circular 0<e<1: elíptica e=1: parabólica e>1: hiperbólica. Vetor e aponta para o perigeu (periapsis). Linha definida por e - linha dos apsides
    self.e_mod = np.linalg.norm(self.e)                       #módulo do vetor excentricidade
    self.a = self.j.dot(self.j)/(mu_terra * np.fabs(1-self.e_mod**2)) #Semieixo maior
    self.b = self.a * np.sqrt(np.fabs(1 - self.e_mod**2))       #Semieixo menor
    self.w = np.sqrt((mu_terra)/self.a**3)                  #Frequência da órbita ou movivento médio. Lembre-se: que Gm = mu_terra

    T = 2 * np.pi * np.sqrt(self.a**3/mu_terra)               #Período da órbita

    self.a_vec = self.a * self.e/self.e_mod #Velocidade na direção do vetor excentricidade, aponta patra o eixo maior da elipse
    self.b_vec = np.cross(self.j, self.e) * self.b/np.linalg.norm(np.cross(self.j, self.e)) #Aponta para o eixo menor da elipse

  def get_elliptical_pos_vel(self, dt): #Descobre onde o satélite está depois de um tempo. Pág 126 do pdf
    if dt == 0:
        self.e_anomalia0 = (self.a - self.r_mod) / (self.e_mod * self.a)

        if self.e_anomalia0 >= 1.0:
            self.e_anomalia0 = 0.0
        elif self.e_anomalia0 <= -1.0:
            self.e_anomalia0 = np.pi
        else:
            self.e_anomalia0 = np.arccos(self.e_anomalia0)

        self.m_anomalia0 = (self.e_anomalia0 - self.e_mod * np.sin(self.e_anomalia0))
    self.m_anomalia = self.m_anomalia0 + dt * self.w

    # Chute inicial para o uso de Newton-Raphson
    e_anomalia_new = 0

    if self.e_mod > 0.8:
        e_anomalia_new = np.pi
    else:
        e_anomalia_new = self.m_anomalia

    d = 1e4
    iteration = 0

    while np.fabs(d) > TOL_KEPLER:
        d = (e_anomalia_new - self.e_mod * np.sin(e_anomalia_new) - self.m_anomalia)
        e_anomalia_new -= d / (1.0 - self.e_mod * np.cos(e_anomalia_new))
        iteration += 1
        if iteration - 1 >= ITERACOES:
            break

    self.e_anomalia = e_anomalia_new
    cos_e = np.cos(self.e_anomalia)
    sin_e = np.sin(self.e_anomalia)

    r_const = cos_e - self.e_mod
    v_const = self.w / (1.0 - self.e_mod * cos_e)
    self.r = self.a_vec * r_const + self.b_vec * sin_e
    self.v = (-self.a_vec * sin_e + self.b_vec * cos_e) * v_const

  def get_hyperbolic_pos_vel(self, dt):
    if dt == 0:
      rdotv = self.r.dot(self.v)
      self.e_anomalia0 = (self.a + self.r_mod) / (self.e_mod * self.a)
      if self.e_anomalia0 < 1.0:
        self.e_anomalia0 = 0.0
      elif rdotv < 0:
        self.e_anomalia0 = -np.arccosh(self.e_anomalia0)
      else:
        self.e_anomalia0 = np.arccosh(self.e_anomalia0)
      self.m_anomalia0 = (self.e_mod * np.sinh(self.e_anomalia0) - self.e_anomalia0)
    self.m_anomalia = self.m_anomalia0 + dt * self.w

    # Solução da equação de Kepler hiperbólica
    # M = e*sinh(F) - F

    M = self.m_anomalia
    e = self.e_mod

    if e <= 1.0:
        raise ValueError("A solução hiperbólica exige e > 1.")

    # Caso trivial
    if M == 0.0:
        F = 0.0
    else:
        sinal = np.sign(M)
        M_abs = np.abs(M)

    # --------------------------------------------------
    # 1. Escolha de um chute inicial estável
    # --------------------------------------------------

        delta_e = e - 1.0

        # Aproximação linear para F pequeno:
        # M ≈ (e - 1)F
        F_linear = M_abs / delta_e

        # Comparação entre os termos linear e cúbico:
        # M ≈ (e - 1)F + e*F³/6
        limite_cubico = 6.0 * delta_e / e

        if M_abs < 1.0:

            if F_linear**2 < limite_cubico:
                # Termo linear dominante
                F = sinal * F_linear

            else:
                # Termo cúbico dominante
                F = sinal * np.cbrt(6.0 * M_abs / e)

        else:
            # Boa aproximação para anomalias maiores
            F = sinal * np.arcsinh(M_abs / e)

    # --------------------------------------------------
    # 2. Newton-Raphson com avaliação numericamente estável
    # --------------------------------------------------

        for iteration in range(ITERACOES):

        # Quando F é pequeno, calcular diretamente
        #
        # e*sinh(F) - F
        #
        # provoca cancelamento numérico.
        #
        # Reescrevemos:
        #
        # e*sinh(F) - F
        # = (e - 1)F + e[sinh(F) - F]

            if np.abs(F) < 0.5:

                F2 = F * F

            # Série de Taylor:
            #
            # sinh(F) - F =
            # F³/6 + F⁵/120 + F⁷/5040 + ...
                sinh_menos_F = F * F2 * (1.0/6.0 + F2 * (1.0/120.0 + F2 * (1.0/5040.0 + F2*(1.0/362880.0+F2*(1.0/39916800.0 + F2/6227020800.0)))))
            else:
                sinh_menos_F = np.sinh(F) - F

        # f(F) = e*sinh(F) - F - M
            f = (e - 1.0) * F + e * sinh_menos_F - M

        # Em vez de:
        #
        # e*cosh(F) - 1
        #
        # usamos:
        #
        # (e - 1) + e[cosh(F) - 1]
        #
        # e calculamos cosh(F)-1 de forma estável:
        #
        # cosh(F)-1 = 2*sinh²(F/2)

            cosh_menos_1 = 2.0 * np.sinh(F / 2.0)**2
            derivada = (e - 1.0) + e * cosh_menos_1

        # Correção de Newton
            correcao = f / derivada
            F_novo = F - correcao

        # Critério de convergência
            if np.abs(correcao) < TOL_KEPLER * (1.0 + np.abs(F_novo)):
                F = F_novo
                break
            F = F_novo
        else:
            raise RuntimeError("A equação de Kepler hiperbólica não convergiu.")
    self.e_anomalia = F

    cos_e = np.cosh(self.e_anomalia)
    sin_e = np.sinh(self.e_anomalia)
    v_const = self.w / (self.e_mod * cos_e - 1.)

    # New position and velocity
    self.r = self.a_vec * (self.e_mod - cos_e) + self.b_vec * sin_e
    self.v = (-self.a_vec * sin_e + self.b_vec * cos_e) * v_const
